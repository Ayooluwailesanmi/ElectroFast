          ),
          tableOutput("ssm_table"),
          h6("Standards"), std_table_ui("ssm_std")
        )
      )
    )
  )

panel_precision = function() nav_panel("Precision",
    layout_sidebar(
      sidebar = sidebar(width = 320,
        numericInput("chk_conc", "Check standard concentration (M)", 1e-3, min = 0),
        textInput("chk_letters", "Readings of the check standard to use (letters, or blank for all)", ""),
        helpText("With the A to O coding, the default readings are I, X and Z. Y is left out because Y and Z",
                 "may both be read at the end of a session. Edit the letters to change this."),
        helpText("This tab uses the files loaded on the ISE calibration tab.",
                 "Repeated readings of one standard give repeatability (within-day SD) and intermediate precision (within and between days).",
                 "They come from a linear mixed model with day as a random effect, fitted by REML with lme4 (Carnoli et al. 2024, Anal. Chim. Acta 1304, 342444).",
                 "Reliable estimates need at least 5 days and 2 or more readings per day."),
        downloadButton("prec_csv", "Results (CSV)")
      ),
      uiOutput("prec_notes"),
      h6("Check standard"), tableOutput("prec_metrics"),
      plotOutput("prec_blup", height = "320px", fill = FALSE),
      h6("Calibration across days (common slope, random day baseline)"), tableOutput("prec_cal")
    )
  )

panel_ecsa = function() nav_panel("ECSA",
  div(class = "px-3 pt-3", style = "max-width: 520px;",
    selectInput("ecsa_material", "Electrode material",
                c("Gold" = "gold", "Platinum" = "pt", "Palladium" = "pd", "Rhodium" = "rh", "Iridium" = "ir",
                  "Glassy carbon, graphite, carbon screen-printed or paste, boron-doped diamond" = "carbon",
                  "Other (ITO, other metals, modified surfaces)" = "other"))),
  conditionalPanel("input.ecsa_material == 'gold'",
    layout_sidebar(
      sidebar = sidebar(width = 320,
        file_in("ecsa_file", "CV file (CHI text export or PalmSens .pssession)", accept = c(".txt", ".pssession", ".mpt", ".mpr", ".dta", ".DTA")),
        numericInput("ecsa_qref", "Charge density (µC/cm²)", 390, min = 1),
        electrode_ui("ecsa_el", "Electrode (for the roughness factor)"),
        textInput("ecsa_ref", "Reference electrode", "Ag/AgCl"),
        textInput("ecsa_title", "Plot title", "Au electrode in 0.5 M H₂SO₄"),
        helpText("The charge is the whole oxide reduction peak on the last cathodic sweep, above a straight baseline.",
                 "ECSA = Q / charge density (390 µC/cm² for gold, Trasatti and Petrii 1991).",
                 "For gold the peak is found automatically. For other metals choose the metal above."),
        downloadButton("ecsa_png", "Plot (PNG)"), downloadButton("ecsa_pdf", "Plot (PDF)"),
        downloadButton("ecsa_csv", "Results (CSV)")),
      card(plotOutput("ecsa_plot", height = "520px", fill = FALSE)),
      card(card_header("Results"), tableOutput("ecsa_table")))),
  conditionalPanel("['pt', 'pd', 'rh', 'ir'].indexOf(input.ecsa_material) >= 0",
    div(class = "px-3", uiOutput("ecsa_metal_help")),
    layout_sidebar(
      sidebar = sidebar(width = 330,
        file_in("sa_files", "CV text exports (one or more)", multiple = TRUE, accept = file_types),
        selectInput("sa_preset", "Method and metal", ecsa_choices(), selected = "pd_ox424"),
        numericInput("sa_q", "Charge density (µC/cm²)", 424, min = 1),
        layout_columns(numericInput("sa_from", "Window from (V)", 0.60, step = 0.01),
                       numericInput("sa_to", "to (V)", 0.10, step = 0.01)),
        radioButtons("sa_dir", "Sweep", c("Last cathodic sweep" = "cathodic", "Last anodic sweep" = "anodic"), inline = TRUE),
        electrode_ui("sa_el", "Electrode (for the roughness factor)"),
        helpText("Charge of the peak between the two potentials on the last full sweep, above a straight baseline",
                 "joining the window ends. ECSA = Q / charge density. Charge densities from Lukaszewski et al. 2016",
                 "(Trasatti and Petrii 1991). Set the window to your own CV: the potentials of the hydrogen, oxide and",
                 "stripping regions depend on the reference electrode and the electrolyte.",
                 "For carbon, or any surface without such a peak, use the Double-layer capacitance tab or a redox probe",
                 "in the CV tab (electroactive area)."),
        downloadButton("sa_csv", "Results (CSV)"), downloadButton("sa_png", "Plot (PNG)")),
      card(plotOutput("sa_plot", height = "460px", fill = FALSE)),
      card(card_header("Results"), tableOutput("sa_table")))),
  conditionalPanel("['carbon', 'other'].indexOf(input.ecsa_material) >= 0",
    card(
      p("These surfaces have no surface reaction with a known charge per cm². The area comes from a redox probe in a",
