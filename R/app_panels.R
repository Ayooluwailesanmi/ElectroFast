        )
      ),
      nav_panel("Separate solution (SSM)",
        layout_sidebar(
          sidebar = sidebar(width = 320,
            file_in("ssm_files", "EMF16 files: interfering ion alone, varied", multiple = TRUE, accept = ".txt"),
            numericInput("ssm_zB", "Charge of the interfering ion", 1),
            textInput("ssm_concs", "Concentrations to compare (M)", "1e-3, 1e-2, 1e-1"),
