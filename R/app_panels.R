                  layout_columns(numericInput("rt_drift", "Settled when drift is below (mV/min)", 1, min = 0.01, step = 0.1),
                                 numericInput("rt_share", "Share of fitted standards settled", 0.9, min = 0.1, max = 1, step = 0.05),
                                 numericInput("rt_flag", "Flag a day when the slope changes by more than (mV/decade)", 2, min = 0.1)),
                  tableOutput("rt_suggest"),
                  plotOutput("rt_plot", height = "380px", fill = FALSE),
                  h6("Slope spread from 120 s on, each day"), tableOutput("rt_spread"),
                  h6("Settling time of each standard"), tableOutput("rt_settle"),
                  downloadButton("rt_csv", "Settling and slope by time (CSV)")),
        nav_panel("Standards", std_table_ui("cal_std")),
        nav_panel("Possible causes",
          p("Each day is checked for the signs below, using the files and settings of this tab. Flagged signs are combined into",
            "things to check. These are prompts, not diagnoses: the same sign can have several causes. The cut-offs are this",
            "app's defaults, not published standards, and can be changed here.", class = "small text-muted"),
          layout_columns(col_widths = c(2, 2, 2, 2, 2, 2),
            numericInput("dx_slope_lo", "Slope below (% Nernstian)", 90, step = 1),
            numericInput("dx_low", "Low-end ratio below", 0.6, step = 0.05),
            numericInput("dx_bg", "Background above (x lowest day)", 3, step = 0.5),
            numericInput("dx_drift", "Check-standard drift beyond (mV)", 5, step = 1),
            numericInput("dx_r2", "R² below", 0.98, step = 0.005),
            numericInput("dx_unsettled", "Unsettled share above", 0.2, step = 0.05)),
          h6("Signs, day by day"), tableOutput("dx_signs"),
          h6("Things to check"), tableOutput("dx_causes"),
          p("Slope is also flagged above 200 minus the lower cut-off (110% by default).",
            "Low-end ratio: slope over the three lowest fitted standards / slope over the whole fit. Background: b of the day",
            "over the lowest b of the days loaded (needs the background-corrected fit). Check-standard drift: Z minus X.",
            "Unsettled: share of fitted standards still drifting at the reading time (rule on the Reading time tab).",
            class = "small text-muted"))
      )
    )
  )

panel_selectivity = function() nav_panel("Selectivity",
    navset_card_tab(
      nav_panel("Fixed interference (FIM)",
        layout_sidebar(
          sidebar = sidebar(width = 320,
            file_in("fim_files", "EMF16 files: primary ion varied, interferent fixed", multiple = TRUE, accept = ".txt"),
            numericInput("fim_cB", "Interferent concentration (M)", 0.001, min = 0),
            numericInput("fim_zB", "Charge of the interfering ion", 1),
            textInput("fim_flat", "Standards on the interferent plateau", "A, B, C, D, E, F"),
            textInput("fim_nernst", "Standards on the Nernstian line", "H, I"),
            helpText("IUPAC fixed interference method (Umezawa et al. 2000, eq. 2): the plateau and the",
                     "Nernstian line are extended until they cross. K = a(A) / a(B)^(zA/zB). Reading time,",
                     "temperature and zA are taken from the ISE calibration tab."),
