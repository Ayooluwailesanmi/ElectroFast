# The editable standards table (shared by the ISE panels)
std_table_ui = function(id) DT::DTOutput(id)

# Panels that sit inside Techniques: the ISE (potentiometry) panels and the merged ECSA panel (gold found automatically;
# other metals by the window method; carbon and other surfaces pointed to the redox-probe and capacitance tabs)

panel_ise_cal = function() nav_panel("ISE calibration",
    layout_sidebar(
      sidebar = sidebar(width = 320,
        helpText(tags$b("How to use."), "1. Upload the files of one or more days.",
                 "2. Give each file its concentration. The surest way is a sample sheet: a CSV listing each file and its",
                 "concentration (download the template). Without a sheet, the concentrations come from the source below,",
                 "which is chosen from the file names.",
                 "3. Check the Standards tab, where any concentration can be corrected (double-click a cell).",
                 "4. Read the slope and the plot."),
        file_in("cal_files", "Data files, one or more days (EMF16 .txt, or any text/CSV with time and potential)",
                  multiple = TRUE, accept = c(".txt", ".csv", ".dat")),
        fileInput("cal_sheet", "Sample sheet (recommended): CSV with the columns file and conc_M, and optionally day, include, fit", accept = ".csv"),
        downloadButton("sheet_template", "Sample-sheet template (CSV)", class = "btn-sm mb-2"),
        radioButtons("scheme", "Without a sample sheet, concentrations come from",
                     c("The concentration written in each file name (for example 1 mM or 1e-3 M)" = "names",
                       "A decade series from 1e-9 M upward in recording order (a suggestion to check)" = "order",
                       "Letter codes A to I = 1e-9 to 1e-1 M, one per decade" = "july",
                       "Letter codes A to O = 1e-9 to 0.5 M with half-decade steps, and X, Y, Z = 1e-3 M check" = "protocol")),
        numericInput("read_s", "Read EMF at (s)", 120, min = 1),
        numericInput("temp", "Temperature (°C)", 25),
        numericInput("zA", "Charge of the primary ion", 1),
        numericInput("bgI", "Background ionic strength (M)", 0, min = 0),
        radioButtons("xaxis", "x-axis", c("−log a (activity, Davies)" = "neg_log_a", "−log c" = "neg_log_c")),
        helpText("Activities use the Davies equation (A = 0.508 at 25 °C), valid to about 0.5 M ionic strength. The ionic strength",
                 "assumes 1:1 salts. For a salt such as Mg(ClO₄)₂, enter its ionic strength as the background."),
        conditionalPanel("['july', 'protocol'].indexOf(input.scheme) >= 0",
          textInput("fit_letters", "Standards in the fit", "E, F, G, H, I"),
          textInput("cmp_letters", "Second range shown alongside (optional)", "F, G, H, I")),
        conditionalPanel("['names', 'order'].indexOf(input.scheme) >= 0",
          layout_columns(numericInput("fit_cfrom", "Fit from (M)", 1e-5, min = 0), numericInput("fit_cto", "to (M)", 0.1, min = 0))),
        checkboxInput("bg_fit", "Also fit the background-corrected model to all standards (Dagar et al. 2026)", TRUE),
        helpText("Concentrations follow the coding chosen above.",
                 "If your design differs, edit conc_M or include in the Standards tab (double-click a cell)."),
        downloadButton("cal_csv", "Results (CSV)"), downloadButton("cal_png", "Plot (PNG)"),
        downloadButton("cal_pdf", "Plot (PDF)")
      ),
      navset_card_tab(
        nav_panel("Calibration", plotOutput("cal_plot", height = "480px", fill = FALSE),
                  h6("Summary over days"), tableOutput("cal_summary"),
                  h6("Each day"), tableOutput("cal_perday"),
                  h6("Second range"), tableOutput("cal_cmp"),
                  h6("Background-corrected fit, E = E0 + S log(x + b), all included standards (dashed curves)"),
                  tableOutput("cal_bg"), tableOutput("cal_bg_perday"),
                  downloadButton("cal_bg_csv", "Background-corrected fit (CSV)")),
        nav_panel("Steps", helpText("Change between neighbouring standards against 59.16/z mV per decade of change (25 °C)."),
                  tableOutput("cal_steps")),
        nav_panel("Time traces", selectInput("trace_day", "Day", choices = NULL),
                  plotOutput("trace_plot", height = "480px", fill = FALSE)),
        nav_panel("Reading time",
                  helpText("A standard has settled once its drift stays below the set rate until the end of the recording.",
