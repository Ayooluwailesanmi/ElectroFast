        "capacitance gives a rough value."),
      div(actionButton("ecsa_go_cv", "Peaks and kinetics: area from a redox probe (Randles–Ševčík)", class = "btn-sm mb-1"),
          actionButton("ecsa_go_ca", "Chronoamperometry: area from a potential step (Cottrell)", class = "btn-sm mb-1"),
          actionButton("ecsa_go_dl", "Double-layer capacitance: approximate area", class = "btn-sm mb-1")))))
