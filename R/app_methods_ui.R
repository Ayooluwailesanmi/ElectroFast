# User interface of the technique tabs: surface area (monolayer charge and double-layer
# capacitance), cyclic voltammetry (peaks, scan rate, k0, electroactive area, adsorbed
# species), Tafel, pulse voltammetry calibration, open-circuit potential,
# chronoamperometry (with Cottrell and microelectrode equations), chronocoulometry,
# chronopotentiometry, rotating disk, RRDE, impedance and a list of the equations used.
# Every tab that needs an area has the shared electrode panel (R/app_electrode.R). The
# server side is in app_methods_server.R.

file_types = c(".txt", ".csv", ".dat", ".pssession", ".mpt", ".mpr", ".dta", ".DTA", ".abf")
# an upload box with a line under it saying how each file was read (filled in by the server, see readas_line)
file_in = function(id, ...) tagList(fileInput(id, ...), uiOutput(paste0(id, "_readas"), class = "small text-muted", style = "margin-top: 0.35rem; margin-bottom: 0.75rem; line-height: 1.35;"))
conc_help = helpText("Concentrations are suggested from the file names (for example '+ 50mM EtOH' gives 50, a file",
                     "without an added amount in such a series is the blank, 0). Check them in the table: double-click",
                     "a cell to change the concentration, or set include to FALSE to leave a file out.")
# (a function, because Shiny loads R/ in alphabetical order and electrochem.R comes later)
ecsa_choices = function() c(stats::setNames(ecsa_references$key, ecsa_references$label), "Other (enter below)" = "other")
probe_inputs = function(p) tagList(
  numericInput(paste0(p, "_n"), "Electrons transferred (n)", 1, min = 1),
  numericInput(paste0(p, "_C"), "Concentration of the redox species (mM)", 1, min = 0),
  selectInput(paste0(p, "_probe"), "Diffusion coefficient", stats::setNames(redox_probes$key, redox_probes$label)),
  numericInput(paste0(p, "_D"), "D (cm²/s)", 7.6e-6, min = 0),
  numericInput(paste0(p, "_T"), "Temperature (°C)", 25))
solve_for = function(id) radioButtons(id, "Solve for", c("Electroactive area (D known)" = "area", "D (area known)" = "D"), inline = TRUE)

